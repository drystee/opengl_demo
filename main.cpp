// camera settings
glm::vec3 cameraPos(0.0f, 1.0f, 5.0f);
glm::vec3 cameraFront(0.0f, 0.0f, -1.0f);
glm::vec3 cameraUp(0.0f, 1.0f, 0.0f);
float deltaTime = 0.0f;
float lastFrame = 0.0f;

// Player cube settings
glm::vec3 playerPos(0.0f, 1.0f, 0.0f);
